-- Canonical schema for empty databases only. Existing databases require explicit
-- verification and baseline at version 1; this file must never be replayed there.
-- Java lifecycle callbacks supply timestamps/booleans; no SQL defaults are added.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    username varchar(50) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE ai_insights (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_at timestamp(6) NOT NULL,
    insight_text text NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT fk_ai_insights_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_ai_insights_user_generated_at ON ai_insights (user_id, generated_at);

CREATE TABLE budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category varchar(50) NOT NULL,
    created_at timestamp(6) NOT NULL,
    budget_month date NOT NULL,
    monthly_limit numeric(19,4) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT budgets_category_check CHECK (category IN ('FOOD','RENT','HOUSING','UTILITIES','GROCERIES','DINING','TRANSPORTATION','HEALTHCARE','INSURANCE','DEBT_PAYMENT','ENTERTAINMENT','SHOPPING','HEALTH','EDUCATION','TRAVEL','SALARY','INVESTMENT_INCOME','TRANSFER','OTHER')),
    CONSTRAINT uk_budgets_user_category_month UNIQUE (user_id, category, budget_month),
    CONSTRAINT fk_budgets_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_budgets_user_month ON budgets (user_id, budget_month);

CREATE TABLE investments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    purchase_date date NOT NULL,
    purchase_price numeric(19,4) NOT NULL,
    shares numeric(19,6) NOT NULL,
    ticker varchar(20) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT ck_investments_shares_positive CHECK (shares > 0),
    CONSTRAINT ck_investments_purchase_price_positive CHECK (purchase_price > 0),
    CONSTRAINT fk_investments_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_investments_user_purchase_date ON investments (user_id, purchase_date);
CREATE INDEX idx_investments_user_ticker ON investments (user_id, ticker);

CREATE TABLE market_quote_snapshots (
    symbol varchar(20) PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    currency varchar(3) NOT NULL,
    fetched_at timestamp(6) with time zone NOT NULL,
    market_timestamp timestamp(6) with time zone,
    previous_close numeric(36,12),
    price numeric(36,12) NOT NULL,
    source varchar(32) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    confirmed_close boolean,
    session_date date
);

CREATE TABLE notification_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_key varchar(200) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT uk_notification_receipts_user_key UNIQUE (user_id, reference_key),
    CONSTRAINT fk_notification_receipts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    message varchar(1000) NOT NULL,
    is_read boolean NOT NULL,
    related_entity_id bigint,
    severity varchar(20) NOT NULL,
    target_path varchar(100) NOT NULL,
    title varchar(100) NOT NULL,
    type varchar(20) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT notifications_severity_check CHECK (severity IN ('INFO','WARNING','ERROR')),
    CONSTRAINT notifications_type_check CHECK (type IN ('BUDGET','RECURRING','SYSTEM')),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_notifications_user_created ON notifications (user_id, created_at, id);
CREATE INDEX idx_notifications_user_read ON notifications (user_id, is_read);

CREATE TABLE recurring_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean NOT NULL,
    amount numeric(19,4) NOT NULL,
    category varchar(50) NOT NULL,
    created_at timestamp(6) NOT NULL,
    description varchar(500),
    end_date date,
    frequency varchar(20) NOT NULL,
    last_generated_date date,
    merchant varchar(150),
    next_occurrence date NOT NULL,
    start_date date NOT NULL,
    type varchar(20) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT recurring_transactions_category_check CHECK (category IN ('FOOD','RENT','HOUSING','UTILITIES','GROCERIES','DINING','TRANSPORTATION','HEALTHCARE','INSURANCE','DEBT_PAYMENT','ENTERTAINMENT','SHOPPING','HEALTH','EDUCATION','TRAVEL','SALARY','INVESTMENT_INCOME','TRANSFER','OTHER')),
    CONSTRAINT recurring_transactions_frequency_check CHECK (frequency IN ('WEEKLY','BIWEEKLY','MONTHLY','YEARLY')),
    CONSTRAINT recurring_transactions_type_check CHECK (type IN ('INCOME','EXPENSE')),
    CONSTRAINT fk_recurring_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_recurring_transactions_due ON recurring_transactions (active, next_occurrence, id);
CREATE INDEX idx_recurring_transactions_user_next ON recurring_transactions (user_id, next_occurrence);

CREATE TABLE transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount numeric(19,4) NOT NULL,
    category varchar(50) NOT NULL,
    created_at timestamp(6) NOT NULL,
    transaction_date date NOT NULL,
    description varchar(500),
    merchant varchar(150),
    type varchar(20) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT transactions_category_check CHECK (category IN ('FOOD','RENT','HOUSING','UTILITIES','GROCERIES','DINING','TRANSPORTATION','HEALTHCARE','INSURANCE','DEBT_PAYMENT','ENTERTAINMENT','SHOPPING','HEALTH','EDUCATION','TRAVEL','SALARY','INVESTMENT_INCOME','TRANSFER','OTHER')),
    CONSTRAINT transactions_type_check CHECK (type IN ('INCOME','EXPENSE')),
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_transactions_user_category ON transactions (user_id, category);
CREATE INDEX idx_transactions_user_date ON transactions (user_id, transaction_date);
